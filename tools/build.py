#!/usr/bin/env python3
"""
Rebuild the website data and download files after editing any SKILL.md.

    python3 tools/build.py

Reads   plugins/moons2star-consulting/skills/*/SKILL.md  and  tools/catalog.json
Writes  docs/assets/skills-data.js
        docs/downloads/moons2star-consulting.zip      (whole plugin)
        docs/downloads/skills/<skill>.zip             (one per skill, for Claude Settings > Skills upload)
"""
import json, os, re, zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PLUGIN = "moons2star-consulting"
PLUGIN_DIR = os.path.join(ROOT, "plugins", PLUGIN)
SKILLS_DIR = os.path.join(PLUGIN_DIR, "skills")
DOCS = os.path.join(ROOT, "docs")
FIXED_DATE = (2026, 11, 6, 0, 0, 0)  # stable zips = clean git diffs


def zwrite(z, arcname, path):
    info = zipfile.ZipInfo(arcname, FIXED_DATE)
    info.compress_type = zipfile.ZIP_DEFLATED
    info.external_attr = 0o644 << 16
    with open(path, "rb") as f:
        z.writestr(info, f.read())


def main():
    cat = json.load(open(os.path.join(ROOT, "tools", "catalog.json"), encoding="utf-8"))
    meta = {s["id"]: s for s in cat["skills"]}
    on_disk = sorted(d for d in os.listdir(SKILLS_DIR) if os.path.isfile(os.path.join(SKILLS_DIR, d, "SKILL.md")))

    missing = [d for d in on_disk if d not in meta]
    if missing:
        print("WARNING: skills without catalog entry (add them to tools/catalog.json):", missing)

    skills = []
    for s in cat["skills"]:
        p = os.path.join(SKILLS_DIR, s["id"], "SKILL.md")
        if not os.path.exists(p):
            print("WARNING: catalog entry without SKILL.md:", s["id"]); continue
        text = open(p, encoding="utf-8").read()
        m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
        if not m or f"name: {s['id']}" not in m.group(1):
            raise SystemExit(f"Frontmatter problem in {p}: name must equal folder name")
        body = text[m.end():].strip()
        refdir = os.path.join(SKILLS_DIR, s["id"], "references")
        refs = []
        if os.path.isdir(refdir):
            for fn in sorted(os.listdir(refdir)):
                if fn.endswith(".md"):
                    refs.append({"name": fn, "text": open(os.path.join(refdir, fn), encoding="utf-8").read().strip()})
        skills.append(dict(s, body=body, deep=bool(refs), refs=refs))

    os.makedirs(os.path.join(DOCS, "assets"), exist_ok=True)
    data = {"plugin": PLUGIN, "packs": cat["packs"], "skills": skills}
    with open(os.path.join(DOCS, "assets", "skills-data.js"), "w", encoding="utf-8") as f:
        f.write("// Generated by tools/build.py - do not edit by hand\nwindow.TOOLKIT = ")
        json.dump(data, f, ensure_ascii=False)
        f.write(";\n")

    dl = os.path.join(DOCS, "downloads"); os.makedirs(os.path.join(dl, "skills"), exist_ok=True)
    for s in skills:
        sdir = os.path.join(SKILLS_DIR, s["id"])
        with zipfile.ZipFile(os.path.join(dl, "skills", s["id"] + ".zip"), "w") as z:
            for base, _, files in sorted(os.walk(sdir)):
                for fn in sorted(files):
                    if fn.startswith("."): continue
                    full = os.path.join(base, fn)
                    zwrite(z, os.path.join(s["id"], os.path.relpath(full, sdir)), full)

    with zipfile.ZipFile(os.path.join(dl, PLUGIN + ".zip"), "w") as z:
        for base, _, files in sorted(os.walk(PLUGIN_DIR)):
            for fn in sorted(files):
                if fn.startswith("."): continue
                full = os.path.join(base, fn)
                zwrite(z, os.path.join(PLUGIN, os.path.relpath(full, PLUGIN_DIR)), full)

    print(f"Built {len(skills)} skills -> docs/assets/skills-data.js, docs/downloads/")


if __name__ == "__main__":
    main()
